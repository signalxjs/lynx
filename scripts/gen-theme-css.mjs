#!/usr/bin/env node
// Emit a design system's built-in theme palettes as real CSS rules.
//
// Usage (from a package dir, after tsgo + copy-assets):
//   node ../../scripts/gen-theme-css.mjs <themesModule> <exportName> <out.css>
//
// Why this exists (#985): a palette declared in a *stylesheet* is resolved by
// the CSS engine, so a built-in theme paints without JS having to be right
// about anything — including the OS color scheme, which the engine evaluates
// itself through `@media (prefers-color-scheme: …)`. `<ThemeProvider>` keeps
// declaring custom properties inline only for themes that have no rule to
// resolve against (anything registered at runtime).
//
// Two rules per theme:
//
//   .daisy-dark { … }                        ← whenever the name is on the host
//   @media (prefers-color-scheme: dark) {
//     .lynx-zero.scheme-dark-daisy-dark { … }  ← while following the OS
//   }
//
// The second is a COMPOUND selector on purpose. `.lynx-zero` is always on the
// provider's host view, so the rule scores (0,2,0) against the pinned rule's
// (0,1,0) and wins deterministically — no reliance on source order — which is
// what lets the engine's answer override a stale JS theme name. A theme only
// ever gets the media branch for its own variant; it is never selected for the
// opposite scheme.
//
// Output is a build artifact under `dist/` (gitignored). The package's
// `src/styles/index.css` `@import`s it by name, so it must be generated after
// `copy-assets` has put `index.css` in place.
import { mkdir, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { pathToFileURL } from 'node:url';

const [themesModule, exportName, out] = process.argv.slice(2);
if (!themesModule || !exportName || !out) {
    console.error('Usage: gen-theme-css.mjs <themesModule> <exportName> <out.css>');
    process.exit(2);
}

// `pathToFileURL` so the dynamic import works on Windows too — Node's ESM
// loader rejects a raw absolute path there (`D:\…` parses as protocol `d:`).
const mod = await import(pathToFileURL(resolve(themesModule)).href);
const themes = mod[exportName];
if (!Array.isArray(themes)) {
    console.error(
        `gen-theme-css: ${themesModule} has no array export "${exportName}"`,
    );
    process.exit(1);
}

// The token derivation is shared with `<ThemeProvider>`'s inline path so the
// two can't drift — see the module doc there. Reached by monorepo-relative
// path because it is internal to `@sigx/lynx-zero-legacy`: there is no subpath export
// for it, and there shouldn't be one until something outside this repo needs
// to generate theme CSS.
const tokensUrl = new URL(
    '../packages/lynx-zero-legacy/dist/theme/theme-tokens.js',
    import.meta.url,
).href;
let themeCustomProperties;
try {
    ({ themeCustomProperties } = await import(tokensUrl));
} catch (err) {
    console.error(
        'gen-theme-css: @sigx/lynx-zero-legacy has not been built — run `pnpm build`'
        + ' (or `pnpm --filter @sigx/lynx-zero-legacy build`) first.\n'
        + `  tried: ${tokensUrl}\n  cause: ${err.message}`,
    );
    process.exit(1);
}

/** The declaration body shared by a theme's pinned and scheme-scoped rules. */
function declarations(theme) {
    const props = themeCustomProperties(theme);
    const lines = Object.entries(props).map(([k, v]) => `  ${k}: ${v};`);
    // The provider's own surface, as literal properties rather than
    // `var()` self-references — a host must never depend on resolving a
    // custom property it declares itself.
    if (theme.colors?.['base-100']) lines.push(`  background-color: ${theme.colors['base-100']};`);
    if (theme.colors?.['base-content']) lines.push(`  color: ${theme.colors['base-content']};`);
    return lines.join('\n');
}

const blocks = [];
for (const theme of themes) {
    const body = declarations(theme);
    blocks.push(`.${theme.name} {\n${body}\n}`);
    // `variant` decides which scheme this theme answers for; a light theme is
    // never picked for a dark device, so it gets no dark branch.
    blocks.push(
        `@media (prefers-color-scheme: ${theme.variant}) {\n`
        + `  .lynx-zero.scheme-${theme.variant}-${theme.name} {\n`
        + `${body.replace(/^/gm, '  ')}\n`
        + `  }\n}`,
    );
}

const css = '/* AUTO-GENERATED from the theme registry — do not edit.\n'
    + ' * Regenerated by scripts/gen-theme-css.mjs on every build.\n'
    + ' *\n'
    + ' * Pinned rule + @media(prefers-color-scheme) twin per built-in theme.\n'
    + ' * The media rules need `enableCSSRule` (on by default) to encode and a\n'
    + ' * Lynx 4.0+ host to evaluate; @sigx/lynx-zero-legacy\'s <ThemeProvider> falls\n'
    + ' * back to inline custom properties wherever they can\'t. */\n\n'
    + blocks.join('\n\n') + '\n';

const outAbs = resolve(out);
await mkdir(dirname(outAbs), { recursive: true });
await writeFile(outAbs, css);
console.log(
    `gen-theme-css: wrote ${themes.length} theme${themes.length === 1 ? '' : 's'}`
    + ` (${blocks.length} rules) → ${out}`,
);
